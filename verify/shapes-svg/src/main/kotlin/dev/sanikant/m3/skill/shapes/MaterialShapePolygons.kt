data class Pt(val x: Float, val y: Float) {
    operator fun minus(o: Pt) = Pt(x - o.x, y - o.y)
    operator fun plus(o: Pt) = Pt(x + o.x, y + o.y)
    operator fun times(f: Float) = Pt(x * f, y * f)
    fun getDistance() = hypot(x, y)

    companion object {
        val Zero = Pt(0f, 0f)
    }
}

/** 2D linear transform about the origin, matching how MaterialShapes uses Compose's Matrix. */
class Mat(private val a: Float, private val b: Float, private val c: Float, private val d: Float) {
    fun map(p: Pt) = Pt(a * p.x + b * p.y, c * p.x + d * p.y)

    companion object {
        fun rotate(degrees: Float): Mat {
            val r = degrees / 180f * PI.toFloat()
            return Mat(cos(r), -sin(r), sin(r), cos(r))
        }

        fun scale(sx: Float, sy: Float) = Mat(sx, 0f, 0f, sy)
    }
}

fun RoundedPolygon.transformed(m: Mat): RoundedPolygon = transformed { x, y ->
    val p = m.map(Pt(x, y))
    FloatFloatPair(p.x, p.y)
}

